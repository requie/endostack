// The Claude directory plugin: a self-contained folder with only what Claude
// loads (skills without their test fixtures, Claude-format agents in the
// default agents/ folder, README, LICENSE), so the directory's file limits and
// scans see the plugin and nothing else from the repo.
export const CLAUDE_PLUGIN_DIR = 'claude-code/plugin';
const SKIP_DIRS = new Set(['test', 'node_modules', '.git']);
const SKIP_FILES = new Set(['.DS_Store', 'Thumbs.db', 'desktop.ini']);
// Skills left out of the Claude plugin only. make-bot-ui has the user store a
// webhook secret that a local relay reads and sends, which the Claude
// directory always holds for review; other agents still install it.
export const CLAUDE_PLUGIN_SKIP_SKILLS = new Set(['make-bot-ui']);

function listFiles(dir, prefix = '') {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const abs = join(dir, name);
    if (statSync(abs).isDirectory()) {
      if (!SKIP_DIRS.has(name)) out.push(...listFiles(abs, `${prefix}${name}/`));
    } else if (!SKIP_FILES.has(name)) out.push(`${prefix}${name}`);
  }
  return out;
}

function claudePlugin(root, ctx, dist) {
  const base = CLAUDE_PLUGIN_DIR;
  for (const s of ctx.skills) {
    if (CLAUDE_PLUGIN_SKIP_SKILLS.has(s.folder)) continue;
    const dir = join(root, 'skills', s.folder);
    for (const rel of listFiles(dir)) dist[`${base}/skills/${s.folder}/${rel}`] = readFileSync(join(dir, rel), 'utf8');
  }
  for (const a of ctx.agents) dist[`${base}/agents/${a.name}.md`] = dist[`claude-code/agents/${a.name}.md`];
  const readme = join(root, 'packaging', 'claude-plugin', 'README.md');
  if (existsSync(readme)) dist[`${base}/README.md`] = readFileSync(readme, 'utf8');
  if (existsSync(join(root, 'LICENSE'))) dist[`${base}/LICENSE`] = readFileSync(join(root, 'LICENSE'), 'utf8');
  // The directory takes its listing icon from .claude-plugin/icon.png (square
  // PNG, 512 to 2048 px, under 2 MB). assets/logo.png is 512 x 512.
  const icon = join(root, 'assets', 'logo.png');
  if (existsSync(icon)) dist[`${base}/.claude-plugin/icon.png`] = readFileSync(icon);
  dist[`${base}/.claude-plugin/plugin.json`] = json({
    name: META.name,
    displayName: META.displayName,
    version: META.version,
    description: META.description,
    author: { name: META.author.name, url: META.author.url },
    homepage: META.homepage,
    repository: META.repository,
    license: META.license,
    keywords: META.keywords,
  });
}

// The OpenAI Plugins Directory package: a self-contained folder with the root
// Agent Plugins manifest, the skills (with Codex's explicit-only policy files),
// the logo, README and LICENSE. Upload it as a ZIP of the folder's contents.
export const OPENAI_PLUGIN_DIR = 'openai/plugin';

function openaiPlugin(root, ctx, dist) {
  const base = OPENAI_PLUGIN_DIR;
  for (const s of ctx.skills) {
    if (CLAUDE_PLUGIN_SKIP_SKILLS.has(s.folder)) continue;
    const dir = join(root, 'skills', s.folder);
    for (const rel of listFiles(dir)) dist[`${base}/skills/${s.folder}/${rel}`] = readFileSync(join(dir, rel), 'utf8');
    const policy = dist[`codex/skills/${s.folder}/agents/openai.yaml`];
    if (policy) dist[`${base}/skills/${s.folder}/agents/openai.yaml`] = policy;
  }
  const readme = join(root, 'packaging', 'openai-plugin', 'README.md');
  if (existsSync(readme)) dist[`${base}/README.md`] = readFileSync(readme, 'utf8');
  if (existsSync(join(root, 'LICENSE'))) dist[`${base}/LICENSE`] = readFileSync(join(root, 'LICENSE'), 'utf8');
  const logo = join(root, 'assets', 'logo.png');
  if (existsSync(logo)) dist[`${base}/assets/logo.png`] = readFileSync(logo);
  dist[`${base}/plugin.json`] = json({
    $schema: AGENT_PLUGINS_SCHEMA,
    name: META.name,
    version: META.version,
    description: META.description,
    author: { name: META.author.name, url: META.author.url },
    homepage: META.homepage,
    repository: META.repository,
    license: META.license,
    keywords: META.keywords,
    extensions: {
      'com.openai': {
        onboardingSkill: './skills/try-endostack/SKILL.md',
        interface: OPENAI_INTERFACE,
        publication: { release_notes: OPENAI_RELEASE_NOTES },
      },
    },
  });
}

const OPENAI_RELEASE_NOTES = `EndoStack ${META.version}: a skills-only plugin with no MCP server and no hooks. It adds security-first workflows: a router skill (tarique-mode) with 23 playbooks, threat-model and security-review gates, 25 principle skills, and a five-minute demo (try-endostack).`;

export function generate(root) {
  const ctx = { skills: loadSkills(root), agents: loadAgents(root) };
  const dist = {};
  for (const id of Object.keys(gen)) gen[id](ctx, dist);
  claudePlugin(root, ctx, dist);
  openaiPlugin(root, ctx, dist);
  const index = {
    note: GEN_NOTE,
    version: META.version,
    skills: ctx.skills.map((s) => s.folder),
    commandSkills: ctx.skills.filter(isCommandSkill).map((s) => s.folder),
    agents: ctx.agents.map((a) => a.name),
    targets: Object.fromEntries(
      Object.keys(TARGETS).map((id) => [id, Object.keys(dist).filter((p) => p.startsWith(`${id}/`)).sort()]),
    ),
  };
  dist['index.json'] = json(index);
  return { ctx, dist, rootFiles: manifests(ctx) };
}
