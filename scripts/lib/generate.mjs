const gen = {
  'claude-code'(ctx, out) {
    for (const a of ctx.agents) {
      const fm = { name: a.name, description: a.fm.description, model: 'inherit' };
      if (a.readonly) fm.disallowedTools = 'Write, Edit, NotebookEdit';
      out[`claude-code/agents/${a.name}.md`] = frontmatter(fm) + agentPreamble(a, 'claude-code') + bodyOf(a);
    }
  },
  cursor(ctx, out) {
    for (const a of ctx.agents) {
      const fm = { name: a.name, description: a.fm.description, model: 'inherit', readonly: a.readonly };
      out[`cursor/agents/${a.name}.md`] = frontmatter(fm) + agentPreamble(a, 'cursor') + bodyOf(a);
    }
  },
  codex(ctx, out) {
    for (const a of ctx.agents) {
      out[`codex/agents/${a.name}.toml`] = [
        `# ${GEN_NOTE}`,
        `name = ${tomlString(a.name)}`,
        `description = ${tomlString(a.fm.description)}`,
        `developer_instructions = ${tomlMultiline(agentPreamble(a, 'codex') + bodyOf(a))}`,
        '',
      ].join('\n');
    }
    // Command-style skills stay explicit-only in Codex through agents/openai.yaml.
    for (const s of ctx.skills.filter(isCommandSkill)) {
      out[`codex/skills/${s.folder}/agents/openai.yaml`] = `# ${GEN_NOTE}\npolicy:\n  allow_implicit_invocation: false\n`;
    }
  },
  'gemini-cli'(ctx, out) {
    for (const a of ctx.agents) {
      const fm = { name: a.name, description: a.fm.description };
      if (a.readonly) fm.tools = ['read_file', 'glob', 'grep_search', 'run_shell_command'];
      out[`gemini-cli/agents/${a.name}.md`] = frontmatter(fm) + agentPreamble(a, 'gemini-cli') + bodyOf(a);
    }
    for (const s of ctx.skills.filter(isCommandSkill)) {
      out[`gemini-cli/commands/${s.folder}.toml`] = [
        `# ${GEN_NOTE}`,
        `description = ${tomlString(s.fm.description)}`,
        `prompt = ${tomlMultiline(commandBody(s, 'gemini-cli', '{{args}}'))}`,
        '',
      ].join('\n');
    }
  },
  copilot(ctx, out) {
    for (const a of ctx.agents) {
      const fm = { name: a.name, description: a.fm.description };
      if (a.readonly) fm.tools = ['read', 'search', 'execute'];
      const text = frontmatter(fm) + agentPreamble(a, 'copilot') + bodyOf(a);
      out[`copilot/agents/${a.name}.agent.md`] = text;
    }
  },
  'devin-desktop'(ctx, out) {
    for (const s of ctx.skills.filter(isCommandSkill)) {
      out[`devin-desktop/workflows/${s.folder}.md`] =
        frontmatter({ description: s.fm.description }) + commandBody(s, 'devin-desktop', null);
    }
  },
  'roo-code'(ctx, out) {
    for (const s of ctx.skills.filter(isCommandSkill)) {
      out[`roo-code/commands/${s.folder}.md`] =
        frontmatter({ description: s.fm.description, 'argument-hint': 'optional input for the skill' }) +
        commandBody(s, 'roo-code', null);
    }
  },
  opencode(ctx, out) {
    for (const a of ctx.agents) {
      const fm = { description: a.fm.description, mode: 'subagent' };
      if (a.readonly) fm.permission = { edit: 'deny' };
      out[`opencode/agents/${a.name}.md`] = frontmatter(fm) + agentPreamble(a, 'opencode') + bodyOf(a);
    }
    for (const s of ctx.skills.filter(isCommandSkill)) {
      out[`opencode/commands/${s.folder}.md`] =
        frontmatter({ description: s.fm.description }) + commandBody(s, 'opencode', '$ARGUMENTS');
    }
  },
  kiro(ctx, out) {
    for (const a of ctx.agents) {
      const fm = { name: a.name, description: a.fm.description };
      if (a.readonly) fm.tools = ['read', 'shell'];
      out[`kiro/agents/${a.name}.md`] = frontmatter(fm) + agentPreamble(a, 'kiro') + bodyOf(a);
    }
  },
  junie(ctx, out) {
    for (const a of ctx.agents) {
      const fm = { name: a.name, description: a.fm.description };
      if (a.readonly) fm.tools = ['Read', 'Glob', 'Grep', 'Bash'];
      out[`junie/agents/${a.name}.md`] = frontmatter(fm) + agentPreamble(a, 'junie') + bodyOf(a);
    }
    for (const s of ctx.skills.filter(isCommandSkill)) {
      out[`junie/commands/${s.folder}.md`] =
        frontmatter({ description: s.fm.description, allowPromptArgument: true }) + commandBody(s, 'junie', '$prompt');
    }
  },
  aider(ctx, out) {
    const rows = ctx.skills.map((s) => `- \`${s.folder}\`: ${s.fm.description ?? ''}`);
    out['aider/ENDOSTACK.md'] = [
      `<!-- ${GEN_NOTE} -->`,
      '# endostack skills',
      '',
      'endostack skills are Markdown playbooks. Aider does not load them by itself. When the user asks for one of the workflows below, ask them to add the skill file with `/read-only .agents/skills/<name>/SKILL.md` (project install) or `/read-only ~/.agents/skills/<name>/SKILL.md` (user install), then follow it. Steps that need subagents, a structured question tool, or a todo tool run inline: do the subagent briefs one after another yourself and ask questions in plain text.',
      '',
      ...rows,
      '',
    ].join('\n');
  },
  goose(ctx, out) {
    for (const a of ctx.agents) {
      out[`goose/agents/${a.name}.md`] =
        frontmatter({ name: a.name, description: a.fm.description }) + agentPreamble(a, 'goose') + bodyOf(a);
    }
  },
};

