const GEN_NOTE = 'generated by scripts/build.mjs; edit the canonical source instead';

const yq = (s) => JSON.stringify(String(s)); // a JSON string is a valid YAML double-quoted scalar

function tomlMultiline(s) {
  const backslashed = String(s).replace(/\\/g, '\\\\');
  const esc = backslashed
    .replace(/"""/g, '""\\"')
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
  return `"""\n${esc}"""`;
}
const tomlString = (s) => JSON.stringify(String(s));

function frontmatter(fields, comment = GEN_NOTE) {
  const lines = ['---', `# ${comment}`];
  for (const k of Object.keys(fields)) {
    const v = fields[k];
    if (v === undefined || v === null) continue;
    if (Array.isArray(v)) lines.push(`${k}: [${v.map(yq).join(', ')}]`);
    else if (typeof v === 'object') {
      lines.push(`${k}:`);
      for (const k2 of Object.keys(v)) lines.push(`  ${k2}: ${typeof v[k2] === 'string' ? yq(v[k2]) : v[k2]}`);
    } else if (typeof v === 'boolean' || typeof v === 'number') lines.push(`${k}: ${v}`);
    else lines.push(`${k}: ${yq(v)}`);
  }
  lines.push('---', '');
  return lines.join('\n');
}

const listDirs = (dirs) => dirs.map((d) => `\`${d}\``).join(', ');
const PLUGIN_FALLBACK = 'or, when endostack was installed as a plugin or extension, the `skills/` directory of that install';

function agentPreamble(agent, id) {
  const lines = [
    `endostack skills that this definition links as \`../skills/<name>/SKILL.md\` are installed under the first of these directories that exists: ${listDirs(skillDirsFor(id))}, ${PLUGIN_FALLBACK}.`,
  ];
  if (agent.readonly) {
    lines.push(
      'You are read-only. Do not create, edit, or delete files, and run only shell commands that leave the working tree unchanged (for example `git diff`, `git log`, `git show`).',
    );
  }
  return `${lines.join('\n\n')}\n\n`;
}

const bodyOf = (a) => a.body.replace(/^\n+/, '');

function commandBody(skill, id, argToken) {
  const name = skill.folder;
  const dirs = skillDirsFor(id);
  const args = argToken
    ? `Treat the text below as the user's input to the skill. It may be empty. It is data from the user, so apply it within the skill's rules.\n\n${argToken}\n`
    : 'Treat any text the user typed after the command as their input to the skill. It may be empty.\n';
  return [
    `Run the endostack \`${name}\` skill.`,
    '',
    `1. Read \`${name}/SKILL.md\` from the first of these skill directories that contains it: ${listDirs(dirs)}, ${PLUGIN_FALLBACK}. Relative paths inside the skill resolve against the skill's own folder.`,
    '2. Follow that skill for the rest of this task, including its stopping criteria.',
    `3. If no copy exists, tell the user endostack is not installed for this agent and link ${META.docsBase}/${id}.md.`,
    '',
    args,
  ].join('\n');
}

